from __future__ import annotations

import hashlib
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Iterable, Literal

import duckdb
import pandas as pd

from avito_recsys.snapshot_identity import duckdb_pseudonymous_snapshot_id_sql


SamplingUnit = Literal["rows", "users"]

MODEL_COLUMNS = (
    # Prediction artifacts are safe to move to Kaggle: never persist a source
    # snapshot_id, because legacy snapshots embed the raw user_id in it.  The
    # conversion is idempotent for already-pseudonymous prepared datasets.
    f"{duckdb_pseudonymous_snapshot_id_sql('snapshot_id')} AS snapshot_id, "
    "epoch(snapshot_ts)::BIGINT AS snapshot_epoch, "
    "leaf, action, ts, label_leaf, masked_leaf"
)


@dataclass(frozen=True)
class SamplingStats:
    sampling_unit: SamplingUnit
    requested_cap: int
    selected_rows: int
    selected_users: int
    subset_seed: int


def _parquet_source(paths: Iterable[Path]) -> str:
    resolved = [Path(path).resolve() for path in paths]
    if not resolved:
        raise ValueError("At least one parquet path is required")
    missing = [str(path) for path in resolved if not path.exists()]
    if missing:
        raise FileNotFoundError(f"Missing parquet inputs: {missing}")
    # Paths are generated by this project. Escape a quote defensively before
    # embedding them into DuckDB's list literal.
    quoted = ["'" + str(path).replace("'", "''") + "'" for path in resolved]
    return "[" + ",".join(quoted) + "]"


def _sampling_identity_column(con: duckdb.DuckDBPyConnection, source: str) -> str:
    """Prefer an already pseudonymous user key, while supporting legacy data."""
    columns = {
        str(row[0])
        for row in con.execute(
            f"DESCRIBE SELECT * FROM read_parquet({source}, union_by_name=true)"
        ).fetchall()
    }
    for candidate in ("hashed_user_key", "user_key", "user_id"):
        if candidate in columns:
            return candidate
    raise ValueError(
        "Snapshot schema needs one of hashed_user_key, user_key or legacy user_id "
        "for distinct-user sampling"
    )


def validate_temporal_split(
    train_snapshot_dates: Iterable[str],
    validation_snapshot_date: str,
    target_days: int,
) -> None:
    """Reject a split whose training target window reaches validation time."""
    train_dates = [date.fromisoformat(value) for value in train_snapshot_dates]
    if not train_dates:
        raise ValueError("The training split has no snapshots")
    validation_date = date.fromisoformat(validation_snapshot_date)
    if len(train_dates) != len(set(train_dates)):
        raise ValueError("The training split contains a duplicate snapshot date")
    if validation_date in train_dates:
        raise ValueError("Validation snapshot is also present in training")
    last_train_target_exclusive = max(train_dates) + timedelta(days=target_days)
    if last_train_target_exclusive > validation_date:
        raise ValueError(
            "Temporal leakage: the last training target window ends after "
            f"validation starts ({last_train_target_exclusive} > {validation_date})"
        )


def audit_temporal_parquet_boundaries(
    train_paths: list[Path],
    validation_path: Path,
    target_days: int,
) -> dict:
    """Validate the configured split against timestamps stored in parquet."""
    train_source = _parquet_source(train_paths)
    validation_source = _parquet_source([validation_path])
    if validation_path.resolve() in {path.resolve() for path in train_paths}:
        raise ValueError("Validation parquet is also present in training inputs")
    con = duckdb.connect()
    try:
        train_min, train_max, train_rows = con.execute(
            f"""
            SELECT min(snapshot_ts), max(snapshot_ts), count(*)
            FROM read_parquet({train_source})
            """
        ).fetchone()
        validation_min, validation_max, validation_rows = con.execute(
            f"""
            SELECT min(snapshot_ts), max(snapshot_ts), count(*)
            FROM read_parquet({validation_source})
            """
        ).fetchone()
    finally:
        con.close()
    if train_min is None or validation_min is None:
        raise ValueError("Train and validation parquets must be non-empty")
    train_target_end = train_max + timedelta(days=target_days)
    if train_target_end > validation_min:
        raise ValueError(
            "Temporal leakage in parquet contents: the last training target window "
            f"ends at {train_target_end}, validation starts at {validation_min}"
        )
    return {
        "train_snapshot_ts_min": train_min.isoformat(),
        "train_snapshot_ts_max": train_max.isoformat(),
        "train_target_end_exclusive_max": train_target_end.isoformat(),
        "validation_snapshot_ts_min": validation_min.isoformat(),
        "validation_snapshot_ts_max": validation_max.isoformat(),
        "train_rows_all_labels": int(train_rows),
        "validation_rows_all_labels": int(validation_rows),
        "passed": True,
    }


def load_positive_frame(
    paths: list[Path],
    cap: int,
    sampling_unit: SamplingUnit,
    subset_seed: int,
) -> tuple[pd.DataFrame, SamplingStats]:
    """Load a positive training subset with deterministic nested membership.

    ``rows`` preserves the legacy behavior: ``cap`` limits positive user×snapshot
    rows. ``users`` first orders distinct positive users and then includes every
    positive snapshot row for each selected user. Thus user caps made with the
    same paths, DuckDB version and ``subset_seed`` are true nested prefixes.

    Raw ``user_id`` is used only transiently for sampling/counting and is removed
    before the dataframe reaches the Dataset or any persisted prediction file.
    """
    if cap < 0:
        raise ValueError("cap must be non-negative; use 0 for the full pool")
    if sampling_unit not in ("rows", "users"):
        raise ValueError(f"Unsupported sampling_unit: {sampling_unit}")

    source = _parquet_source(paths)
    limit = "" if cap == 0 else f"LIMIT {int(cap)}"
    con = duckdb.connect()
    try:
        user_column = _sampling_identity_column(con, source)
        if sampling_unit == "rows":
            frame = con.execute(
                f"""
                SELECT {MODEL_COLUMNS}, {user_column} AS _sampling_user_key
                FROM read_parquet({source}, union_by_name=true) AS p
                WHERE p.n_labels > 0
                ORDER BY hash(p.snapshot_id || '{int(subset_seed)}'), p.snapshot_id
                {limit}
                """
            ).fetchdf()
        else:
            user_limit = "" if cap == 0 else f"WHERE user_rank <= {int(cap)}"
            frame = con.execute(
                f"""
                WITH positive AS (
                    SELECT *
                    FROM read_parquet({source}, union_by_name=true)
                    WHERE n_labels > 0
                ),
                ranked_users AS (
                    SELECT {user_column} AS _sampling_user_key,
                           row_number() OVER (
                               ORDER BY hash(CAST({user_column} AS VARCHAR) || '{int(subset_seed)}'),
                                        CAST({user_column} AS VARCHAR)
                           ) AS user_rank
                    FROM (SELECT DISTINCT {user_column} FROM positive)
                ),
                selected_users AS (
                    SELECT _sampling_user_key, user_rank
                    FROM ranked_users
                    {user_limit}
                )
                SELECT {MODEL_COLUMNS}, p.{user_column} AS _sampling_user_key
                FROM positive p
                JOIN selected_users s
                  ON p.{user_column} = s._sampling_user_key
                ORDER BY s.user_rank, p.snapshot_ts, p.snapshot_id
                """
            ).fetchdf()
    finally:
        con.close()

    if frame.empty:
        raise ValueError("Sampling produced an empty training dataframe")
    selected_users = int(frame["_sampling_user_key"].nunique())
    if sampling_unit == "users" and cap > 0 and selected_users != cap:
        raise ValueError(
            f"Requested {cap} users but selected {selected_users}; "
            "the cap may exceed the positive-user pool"
        )
    frame = frame.drop(columns=["_sampling_user_key"])
    return frame, SamplingStats(
        sampling_unit=sampling_unit,
        requested_cap=int(cap),
        selected_rows=len(frame),
        selected_users=selected_users,
        subset_seed=int(subset_seed),
    )


def load_fixed_evaluation_frame(paths: list[Path], cap: int) -> pd.DataFrame:
    """Load evaluation independently of train subset/model seeds."""
    if cap < 0:
        raise ValueError("cap must be non-negative; use 0 for the full pool")
    source = _parquet_source(paths)
    limit = "" if cap == 0 else f"LIMIT {int(cap)}"
    con = duckdb.connect()
    try:
        return con.execute(
            f"""
            SELECT {MODEL_COLUMNS}
            FROM read_parquet({source}, union_by_name=true) AS p
            WHERE p.n_labels > 0
            ORDER BY hash(p.snapshot_id), p.snapshot_id
            {limit}
            """
        ).fetchdf()
    finally:
        con.close()


def audit_nested_user_prefixes(
    paths: list[Path],
    caps: Iterable[int],
    subset_seed: int,
) -> dict:
    """Return privacy-safe evidence that user-cap samples are nested prefixes.

    The audit never exports raw user IDs. It streams SHA-256 digests ordered by
    deterministic ``user_rank`` and stores a cumulative digest at each cap.
    """
    requested_caps = sorted(set(int(cap) for cap in caps))
    if not requested_caps or requested_caps[0] <= 0:
        raise ValueError("caps must contain positive integers")
    source = _parquet_source(paths)
    con = duckdb.connect()
    try:
        user_column = _sampling_identity_column(con, source)
        cursor = con.execute(
            f"""
            WITH positive AS (
                SELECT {user_column} AS _sampling_user_key, snapshot_id
                FROM read_parquet({source}, union_by_name=true)
                WHERE n_labels > 0
            ),
            per_user AS (
                SELECT _sampling_user_key, count(*)::BIGINT AS positive_rows
                FROM positive
                GROUP BY _sampling_user_key
            ),
            ranked AS (
                SELECT _sampling_user_key, positive_rows,
                       row_number() OVER (
                           ORDER BY hash(CAST(_sampling_user_key AS VARCHAR) || '{int(subset_seed)}'),
                                    CAST(_sampling_user_key AS VARCHAR)
                       ) AS user_rank
                FROM per_user
            )
            SELECT user_rank,
                   sha256(CAST(_sampling_user_key AS VARCHAR)) AS anonymous_user_digest,
                   positive_rows
            FROM ranked
            ORDER BY user_rank
            """
        )
        running = hashlib.sha256()
        rows_seen = 0
        users_seen = 0
        points: list[dict] = []
        cap_index = 0
        expected_rank = 1
        while batch := cursor.fetchmany(10_000):
            for user_rank, anonymous_digest, positive_rows in batch:
                rank = int(user_rank)
                if rank != expected_rank:
                    raise RuntimeError(
                        f"Non-consecutive user_rank: expected {expected_rank}, got {rank}"
                    )
                expected_rank += 1
                users_seen += 1
                rows_seen += int(positive_rows)
                running.update(str(anonymous_digest).encode("ascii"))
                running.update(b"\n")
                while cap_index < len(requested_caps) and users_seen == requested_caps[cap_index]:
                    points.append(
                        {
                            "user_cap": users_seen,
                            "selected_positive_user_snapshot_rows": rows_seen,
                            "ordered_anonymous_prefix_sha256": running.hexdigest(),
                        }
                    )
                    cap_index += 1
        total_users = users_seen
        total_rows = rows_seen
    finally:
        con.close()

    if requested_caps[-1] > total_users:
        raise ValueError(
            f"Largest cap {requested_caps[-1]} exceeds positive-user pool {total_users}"
        )
    if len(points) != len(requested_caps):
        raise RuntimeError("Not every requested cap was observed during the prefix audit")
    return {
        "sampling_unit": "distinct_positive_user",
        "sampling_identity_column": user_column,
        "included_rows_per_user": "all positive user-snapshot rows in selected train snapshots",
        "subset_seed": int(subset_seed),
        "duckdb_version": duckdb.__version__,
        "total_positive_users": total_users,
        "total_positive_user_snapshot_rows": total_rows,
        "nested_prefixes_verified": True,
        "privacy": (
            "The sampling key is transient. Only its SHA-256 digest enters cumulative "
            "prefix digests; source user IDs and source snapshot IDs are not emitted."
        ),
        "points": points,
    }
